/**
 * 改行を `\n` に揃える。**外から来た字を読む前に必ず通す**。
 *
 * Windows で書いた `.md` も、編集画面を通して保存されたノートも CRLF で来る。
 * **改行の書き方は書き手の間違いではない**ので、読む前にここで揃える。
 *
 * 揃えないと、同じ字を見ているつもりの 2 か所が食い違う:
 * 行を trim して読む部品や配線は通るのに、**行をそのまま使うところ**
 * (注釈の `- source`、エラーに添える行の中身) だけが行末の `\r` を抱えて落ちる。
 * Markdown からフェンスを取り出すところでは、開き記号の行が `(.*)$` に
 * 引っかからず**1 つも見つからないまま黙って終わる**。
 *
 * 1 つの改行が 1 つの `\n` になるだけで**行数は変わらない**ので、
 * 行番号も (回路図の `% line N` の対応も) そのまま使える。
 */
export const normalizeNewlines = (text: string): string => text.replace(/\r\n?/g, '\n');
